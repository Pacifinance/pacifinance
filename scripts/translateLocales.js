// Apply patches
function applyPatches(filename, patches) {
    const data = readLocale(filename);
    let count = 0;
    for (const [path, value] of Object.entries(patches)) {
        deepSet(data, path, value);
        count++;
    }
    writeLocale(filename, data);
    console.log(`✅ Applied ${count} translations to ${filename}`);
}

